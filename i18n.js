/* Normalize dictionary keys so leading/trailing spaces never block a match */
Object.keys(UI_EN).forEach((k) => {
  const nk = k.trim();
  if (nk !== k) {
    if (!(nk in UI_EN)) UI_EN[nk] = UI_EN[k];
    delete UI_EN[k];
  }
});

/* Dynamic patterns that contain numbers or mixed text */
const UI_PATTERNS = [
  [/\b(\d+)\/(\d+) taiyar\b/gi, '$1/$2 ready'],
  [/\b(\d+)% taiyar\b/gi, '$1% ready'],
  [/\b(\d+) \/ (\d+) sahi\b/gi, '$1 / $2 correct'],
  [/\bka quiz khatam\b/gi, ' quiz completed'],
  [/\bFlashcards \((\d+)\)/gi, 'Flashcards ($1)'],
  [/\b(\d+)-bit\b/gi, '$1-bit'],
  [/\b(\d+) sessions?\b/gi, function (m, n) { return n + (n === '1' ? ' session' : ' sessions'); }]
];

function translateText(text) {
  if (!text) return text;
  const lead = (text.match(/^\s*/) || [''])[0];
  const trail = (text.match(/\s*$/) || [''])[0];
  const core = text.trim();
  let out = UI_EN[core] || core;
  if (out === core) {
    for (const [re, rep] of UI_PATTERNS) out = out.replace(re, rep);
  }
  return lead + out + trail;
}
